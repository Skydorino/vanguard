package dev.vanguard.module.impl;

import dev.vanguard.module.Category;
import dev.vanguard.module.Module;
import net.minecraft.client.multiplayer.ClientLevel;
import net.minecraft.client.player.LocalPlayer;
import net.minecraft.network.chat.Component;
import net.minecraft.network.protocol.game.ServerboundSetCreativeModeSlotPacket;
import net.minecraft.world.GameType;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.enchantment.Enchantments;
import net.minecraft.core.component.DataComponents;
import net.minecraft.core.component.DataComponentPatch;
import net.minecraft.world.item.component.ItemEnchantments;

import java.lang.reflect.Field;
import java.util.List;

/**
 * GhostKit — gamemode spoof + creative slot injection.
 *
 * Theory: MultiPlayerGameMode holds a client-side localPlayerMode field.
 * We reflect into it, temporarily set it to CREATIVE, fire
 * ServerboundSetCreativeModeSlotPacket for each kit item directly into
 * hotbar slots 0-8, then restore SURVIVAL immediately.
 *
 * The packets look identical to legitimate creative packets because they
 * ARE legitimate creative packets — generated by the same code path vanilla uses.
 * Whether the server honours them depends entirely on server-side validation.
 * Vanilla and poorly patched Paper servers may accept them. Properly configured
 * anticheats (NCP, Grim, etc.) will drop them.
 *
 * Kit loaded into hotbar slots 0-8:
 *   0: Elytra (Unbreaking III, Mending)
 *   1: Totem of Undying
 *   2: Totem of Undying
 *   3: Splash Potion of Healing II  x3
 *   4: Golden Apple x16
 *   5: Ender Pearl x16
 *   6: Diamond Sword (Sharpness V, Unbreaking III, Mending, Fire Aspect II, Looting III)
 *   7: Diamond Pickaxe (Efficiency V, Unbreaking III, Mending)
 *   8: Bow (Power V, Infinity, Unbreaking III, Flame)
 *
 * Enable once to fire the packets. Module disables itself immediately after.
 */
public class GhostKit extends Module {
    // Reflect into MultiPlayerGameMode to get/set localPlayerMode
    private static Field localPlayerModeField;
    private static Field previousPlayerModeField;

    static {
        try {
            Class<?> gm = net.minecraft.client.multiplayer.MultiPlayerGameMode.class;
            // Mojang mappings field name
            localPlayerModeField = gm.getDeclaredField("localPlayerMode");
            localPlayerModeField.setAccessible(true);
            previousPlayerModeField = gm.getDeclaredField("previousLocalPlayerMode");
            previousPlayerModeField.setAccessible(true);
        } catch (NoSuchFieldException e) {
            // Field name may differ — will be caught at runtime and reported
            localPlayerModeField = null;
        }
    }

    public GhostKit() {
        super("GhostKit", Category.MISC,
            "Spoofs gamemode to CREATIVE and injects a NethPot kit via creative slot packets");
    }

    @Override
    public void onTick(LocalPlayer player, ClientLevel level) {
        setEnabled(false); // fire once then stop

        if (localPlayerModeField == null) {
            player.displayClientMessage(
                Component.literal("[GhostKit] Reflection failed — Mojang field name mismatch. Check logs."), false);
            return;
        }

        try {
            var gm = mc.gameMode;

            // Save real gamemode
            GameType realMode = (GameType) localPlayerModeField.get(gm);

            // Spoof to CREATIVE
            localPlayerModeField.set(gm, GameType.CREATIVE);

            // Build and send kit packets
            List<ItemStack> kit = buildKit();
            for (int slot = 0; slot < Math.min(kit.size(), 9); slot++) {
                // Hotbar slots in the creative packet are 36-44 (inventory indices)
                int packetSlot = 36 + slot;
                mc.getConnection().send(new ServerboundSetCreativeModeSlotPacket(packetSlot, kit.get(slot)));
            }

            // Restore real gamemode immediately
            localPlayerModeField.set(gm, realMode);

            player.displayClientMessage(
                Component.literal("[GhostKit] Packets sent. Check your inventory."), false);

        } catch (Exception e) {
            player.displayClientMessage(
                Component.literal("[GhostKit] Error: " + e.getMessage()), false);
        }
    }

    private List<ItemStack> buildKit() {
        // Elytra
        ItemStack elytra = new ItemStack(Items.ELYTRA);
        enchant(elytra, Enchantments.UNBREAKING, 3);
        enchant(elytra, Enchantments.MENDING, 1);

        // Totems
        ItemStack totem1 = new ItemStack(Items.TOTEM_OF_UNDYING);
        ItemStack totem2 = new ItemStack(Items.TOTEM_OF_UNDYING);

        // Healing potions (splash)
        ItemStack pots = new ItemStack(Items.SPLASH_POTION, 3);
        // Potion effects require registry lookup — set via NBT tag approach
        applyHealingPotion(pots);

        // Golden apples
        ItemStack gaps = new ItemStack(Items.GOLDEN_APPLE, 16);

        // Ender pearls
        ItemStack pearls = new ItemStack(Items.ENDER_PEARL, 16);

        // Diamond sword
        ItemStack sword = new ItemStack(Items.DIAMOND_SWORD);
        enchant(sword, Enchantments.SHARPNESS, 5);
        enchant(sword, Enchantments.UNBREAKING, 3);
        enchant(sword, Enchantments.MENDING, 1);
        enchant(sword, Enchantments.FIRE_ASPECT, 2);
        enchant(sword, Enchantments.LOOTING, 3);

        // Diamond pickaxe
        ItemStack pick = new ItemStack(Items.DIAMOND_PICKAXE);
        enchant(pick, Enchantments.EFFICIENCY, 5);
        enchant(pick, Enchantments.UNBREAKING, 3);
        enchant(pick, Enchantments.MENDING, 1);

        // Bow
        ItemStack bow = new ItemStack(Items.BOW);
        enchant(bow, Enchantments.POWER, 5);
        enchant(bow, Enchantments.INFINITY, 1);
        enchant(bow, Enchantments.UNBREAKING, 3);
        enchant(bow, Enchantments.FLAME, 1);

        return List.of(elytra, totem1, totem2, pots, gaps, pearls, sword, pick, bow);
    }

    /**
     * Applies an enchantment to an ItemStack using the 1.21 DataComponents API.
     * Reads the existing enchantments component, adds the new entry, writes it back.
     */
    private void enchant(ItemStack stack, net.minecraft.core.Holder<net.minecraft.world.item.enchantment.Enchantment> enchantment, int level) {
        ItemEnchantments existing = stack.getOrDefault(DataComponents.ENCHANTMENTS, ItemEnchantments.EMPTY);
        ItemEnchantments.Mutable mutable = new ItemEnchantments.Mutable(existing);
        mutable.set(enchantment, level);
        stack.set(DataComponents.ENCHANTMENTS, mutable.toImmutable());
    }

    /**
     * Sets the potion type on a splash potion stack to Healing II.
     * Uses the POTION data component introduced in 1.20.5+.
     */
    private void applyHealingPotion(ItemStack stack) {
        try {
            // net.minecraft.world.item.alchemy.Potions holds the registry
            var potions = net.minecraft.core.registries.BuiltInRegistries.POTION;
            var key = net.minecraft.resources.ResourceLocation.parse("strong_healing");
            var potion = potions.get(key);
            if (potion != null) {
                stack.set(DataComponents.POTION_CONTENTS,
                    new net.minecraft.world.item.alchemy.PotionContents(
                        java.util.Optional.of(net.minecraft.core.Holder.direct(potion)),
                        java.util.Optional.empty(),
                        java.util.List.of()));
            }
        } catch (Exception ignored) {
            // If potion registry lookup fails just leave it as a plain splash potion
        }
    }
}
